"""Render config.example.toml from the defaults and the ``:ivar`` descriptions of the settings dataclasses.

The example lists every setting with its default, so it is generated rather than written by hand: a default changed
in the code changes the example in the same commit. With ``--check`` the script only compares and fails when the
committed file is stale, which is how the pre-commit gate runs it.

Usage from the repository root::

    uv run scripts/render_config_example.py
    uv run scripts/render_config_example.py --check
"""

import argparse
import enum
import re
import sys
import textwrap
from dataclasses import fields, is_dataclass
from pathlib import Path
from typing import TYPE_CHECKING

from ed2k_client.client import ClientConfig

if TYPE_CHECKING:
    from _typeshed import DataclassInstance

EXAMPLE = Path(__file__).resolve().parent.parent / 'config.example.toml'
ENCODING = 'utf-8'
IVAR = re.compile(r':ivar (\w+): (.+?)(?=\n\s*:ivar|\n\s*$|\Z)', re.DOTALL)
COMMENT_WIDTH = 116
STALE_EXIT = 1

# Settings without a useful default, shown commented out in the header instead
WITHOUT_DEFAULT = frozenset(
    {'state_dir', 'download_dir', 'servers', 'server_met', 'nodes_dat', 'ip_filter', 'allow_private_peers'}
)
HEADER = """\
# Every setting of ed2k-client with its default value, generated by scripts/render_config_example.py. Copy the file,
# keep the keys you change and pass it with --config. A key that is missing keeps its default, and an unknown key or
# a value of the wrong type is refused.
#
# Paths and lists that have no useful default are shown commented out:
# state_dir = '~/.local/state/ed2k-client'
# download_dir = '~/Downloads/ed2k'
# servers = ['ed2k://|server|85.17.116.222|6082|/']
# server_met = '~/server.met'
# nodes_dat = '~/nodes.dat'
# ip_filter = '~/ipfilter.dat'
# allow_private_peers = false
"""


def _comment(text: str) -> list[str]:
    """Turn an ``:ivar`` description into wrapped comment lines that start with a capital.

    :param text: the description.
    :type text: str
    :returns: the comment lines.
    :rtype: list[str]
    """
    text = ' '.join(text.split()).replace('``', '`')
    return [f'# {line}' for line in textwrap.wrap(text[:1].upper() + text[1:], COMMENT_WIDTH)]


def _literal(value: object) -> str:
    """Write a default as a TOML value.

    :param value: the default.
    :type value: object
    :returns: the TOML text.
    :rtype: str
    """
    match value:
        case bool():
            return str(value).lower()
        case enum.Enum():
            return f"'{value.name.lower()}'"
        case str():
            return f"'{value}'"
        case int():
            return f'{value:_}'
        case _:
            return repr(value)


def _table(settings: DataclassInstance) -> list[str]:
    """Write the scalar fields of a settings object with their descriptions.

    :param settings: a settings dataclass instance.
    :type settings: DataclassInstance
    :returns: the lines.
    :rtype: list[str]
    """
    described = dict(IVAR.findall(type(settings).__doc__ or ''))
    lines: list[str] = []
    for item in fields(settings):
        value = getattr(settings, item.name)
        if is_dataclass(value) or item.name in WITHOUT_DEFAULT:
            continue
        lines += [*_comment(described.get(item.name, '')), f'{item.name} = {_literal(value)}']
    return lines


def render() -> str:
    """Render the whole example.

    :returns: the file content.
    :rtype: str
    """
    config = ClientConfig()
    described = dict(IVAR.findall(ClientConfig.__doc__ or ''))
    lines = [HEADER, *_table(config)]
    for item in fields(config):
        value = getattr(config, item.name)
        if is_dataclass(value) and not isinstance(value, type):
            lines += ['', *_comment(described[item.name]), f'[{item.name}]', *_table(value)]
    return '\n'.join(lines) + '\n'


def main() -> int:
    """Write the example, or with ``--check`` report whether the committed one is current.

    :returns: the exit code, 1 when the check finds the file stale.
    :rtype: int
    """
    parser = argparse.ArgumentParser(description='Render config.example.toml from the settings defaults.')
    parser.add_argument('--check', action='store_true', help='fail when the committed example is stale')
    arguments = parser.parse_args()

    text = render()
    if not arguments.check:
        EXAMPLE.write_text(text, encoding=ENCODING)
        return 0

    if EXAMPLE.read_text(encoding=ENCODING) == text:
        return 0
    print(f'{EXAMPLE.name} is stale, run: uv run scripts/render_config_example.py', file=sys.stderr)
    return STALE_EXIT


sys.exit(main())
